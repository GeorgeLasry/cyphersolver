"""Group the targets into cipher families: the connected pieces of the key web in docs/keys.json (a key and every
target it read, helped read, was rebuilt from, or was tried on). Tao (Nature 22 Oct 2026) asks for collaborations
on interconnected problems; these are ours, each one a unit a collaborator could take on whole.

  python research/families/families.py        writes research/families/FAMILIES.md

Each family lists its keys, its read targets, its open ones, and the untried leads on them from
research/patterns/leads.csv (run research/patterns/mine.py first).
"""
import sys, csv, json, pathlib, collections as C

sys.stdout.reconfigure(encoding='utf-8', errors='replace')
ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = pathlib.Path(__file__).resolve().parent

def state(folder):
    try: return (json.loads((ROOT / 'targets' / folder / 'profile.json').read_text(encoding='utf-8')).get('outcome') or {}).get('class', '?')
    except (OSError, ValueError): return '?'

def main():
    kw = json.loads((ROOT / 'docs' / 'keys.json').read_text(encoding='utf-8'))
    label = {k['id']: k for k in kw['keys']}
    who = {}
    for s in kw.get('source_links', []): who.setdefault(s['key'], set()).add(s['source'])
    src = {s['id']: s['label'] for s in kw.get('sources', [])}
    edges = [('k:' + l['key'], 't:' + l['target']) for l in kw['links']] + \
            [('k:' + t['key'], 't:' + t['target']) for t in kw['tried']]
    parent = {}
    def find(x):
        parent.setdefault(x, x)
        while parent[x] != x: parent[x] = parent[parent[x]]; x = parent[x]
        return x
    for a, b in edges: parent[find(a)] = find(b)
    groups = C.defaultdict(set)
    for n in list(parent): groups[find(n)].add(n)
    leads = C.defaultdict(list)
    lp = ROOT / 'research' / 'patterns' / 'leads.csv'
    if lp.exists():
        for r in csv.DictReader(open(lp, encoding='utf-8')): leads[r['target']].append(r['key'])
    fams = []
    for g in groups.values():
        keys = sorted(n[2:] for n in g if n.startswith('k:'))
        tg = sorted(n[2:] for n in g if n.startswith('t:'))
        if len(tg) < 2: continue
        st = {t: state(t) for t in tg}
        read = [t for t in tg if st[t] in ('read', 'already solved')]
        open_ = [t for t in tg if st[t] in ('read in part', 'not read')]
        years = [label[k].get('year') for k in keys if isinstance(label.get(k, {}).get('year'), int)]
        people = sorted({src.get(s, s) for k in keys for s in who.get(k, ())} - {'cyphersolver'})
        fams.append(dict(keys=keys, targets=tg, read=read, open=open_, years=years, people=people,
                         leads={t: leads[t] for t in open_ if leads[t]}))
    fams.sort(key=lambda f: (-len(f['open']), -len(f['targets'])))
    md = ['# Cipher families', '',
          f'Generated by `research/families/families.py` from `docs/keys.json`: {len(fams)} families of two or more targets '
          'joined by a shared key (read with it, rebuilt from it, or tried against it). Largest open families first. '
          'Each is a unit for a joint project: the keys, who holds or published them, what is read and what is open.', '']
    for i, f in enumerate(fams, 1):
        span = f'{min(f["years"])}-{max(f["years"])}' if f['years'] else 'undated'
        md += [f'## {i}. {label.get(f["keys"][0], {}).get("label", f["keys"][0])[:90]}', '',
               f'- span: {span}; {len(f["targets"])} targets, {len(f["read"])} read, {len(f["open"])} open',
               f'- keys: ' + ', '.join(f'`{k}`' for k in f['keys'][:12]) + (' ...' if len(f['keys']) > 12 else ''),
               f'- people: ' + (', '.join(f['people']) or 'project only'),
               f'- read: ' + (', '.join(f['read']) or 'none'),
               f'- open: ' + (', '.join(f['open']) or 'none')]
        for t, ks in f['leads'].items(): md.append(f'  - lead on `{t}`: try ' + ', '.join(f'`{k}`' for k in ks[:3]))
        md.append('')
    (OUT / 'FAMILIES.md').write_text('\n'.join(md), encoding='utf-8')
    print(f'{len(fams)} families -> research/families/FAMILIES.md; largest open: ' +
          '; '.join(f'{len(f["open"])} open/{len(f["targets"])}' for f in fams[:5]))

if __name__ == '__main__':
    main()
