"""Second mining pass over the target profiles: what predicts a successful attack, which techniques work, where the
work fails, and which leads in leads.csv the NOTES show were already tried.

  python research/patterns/deeper.py          writes research/patterns/DEEPER.md, cleans leads.csv (run mine.py first)

Attempted = the project attacked the cipher itself: outcome.method is not "read from existing decipherment" or
"not applicable", and the class is not "not a cipher" or "offline only". Success = class "read" or "read in part"
with a method other than "not solved"; full = class "read". Rates on small groups are shown with their n; read
them as questions, not results.
"""
import sys, csv, json, re, pathlib, collections as C
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import mine

ROOT, OUT = mine.ROOT, mine.OUT
SKIP_METHOD = {'read from existing decipherment', 'not applicable', None}
SKIP_CLASS = {'not a cipher', 'offline only'}

def tokens(prof):
    t = [mine.num((d.get('length') or {}).get('tokens')) for d in prof['documents'] if isinstance(d.get('length'), dict)]
    t = [x for x in t if x]
    return sum(t) if t else None

def bucket(v, edges, unit=''):
    if v is None: return 'unknown'
    for lo, hi in zip(edges, edges[1:]):
        if lo <= v < hi: return f'{lo:g}-{hi:g}{unit}' if hi != float('inf') else f'{lo:g}+{unit}'
    return 'unknown'

def rate_table(groups, label):
    rows = []
    for g, fs in sorted(groups.items(), key=lambda x: -len(x[1])):
        if len(fs) < 4: continue
        ok = sum(f['ok'] for f in fs); full = sum(f['full'] for f in fs)
        rows.append((g, len(fs), f'{100 * ok // len(fs)}%', f'{100 * full // len(fs)}%'))
    return mine.table([label, 'attempted', 'success', 'read in full'], rows)

def main():
    profs = mine.load()
    att = {}
    for f, p in profs.items():
        ft = mine.features(p)
        if ft['method'] in SKIP_METHOD or ft['class'] in SKIP_CLASS: continue
        ft['ok'] = ft['class'] in ('read', 'read in part') and ft['method'] != 'not solved'
        ft['full'] = ft['class'] == 'read'
        ft['tokens'] = tokens(p)
        att[f] = ft
    md = ['# Deeper patterns across the target profiles', '',
          '**Caveat.** Features such as homophones, nulls and symbol kind are mostly established by reading the cipher, '
          'so "unknown" goes with failure by construction. Compare the known values with each other, not with "unknown".', '',
          f'Generated by `research/patterns/deeper.py`. {len(att)} targets the project attacked itself, out of '
          f'{len(profs)} valid profiles. Groups under four are left out. A pattern here is a question to test, '
          'not a finding.', '']

    # 1. what predicts success
    md += ['## 1. What goes with a successful attack', '']
    dims = [
        ('route (conditions.attack)', lambda f: f['attack'] or 'unknown'),
        ('length in tokens', lambda f: bucket(f['tokens'], [0, 100, 300, 1000, 3000, float('inf')])),
        ('homophonic', lambda f: {True: 'yes', False: 'no'}.get(f['homophones'], 'unknown')),
        ('nomenclator entries', lambda f: bucket(f['nomen'], [0, 1, 20, 100, float('inf')])),
        ('symbol kind', lambda f: f['symbols'] or 'unknown'),
        ('century', lambda f: f'{f["year"] // 100 + 1}th c.' if f['year'] else 'unknown'),
        ('nulls', lambda f: {True: 'yes', False: 'no'}.get(f['nulls'], 'unknown')),
    ]
    for name, key in dims:
        g = C.defaultdict(list)
        for f in att.values(): g[key(f)].append(f)
        md += [f'### By {name}', '', rate_table(g, name), '']

    # ciphertext-only specifically
    ct = [f for f in att.values() if f['attack'] == 'ciphertext-only']
    g = C.defaultdict(list)
    for f in ct: g[bucket(f['tokens'], [0, 100, 300, 1000, float('inf')])].append(f)
    md += ['### Ciphertext-only attacks by length', '',
           'The unicity question in practice: below what length did ciphertext-only stop working?', '',
           rate_table(g, 'tokens'), '']

    # 2. techniques
    tech = C.defaultdict(C.Counter); tech_ok = C.Counter(); n_ok = 0
    for f, p in profs.items():
        if f not in att: continue
        steps = [s for s in p.get('solution') or [] if isinstance(s, dict)]
        used = set()
        for s in steps:
            if s.get('kind') not in ('solver', 'hypothesis', 'crib', 'sibling key', 'key from source', 'statistics'): continue
            for t in s.get('technique') or []:
                tech[t][s.get('result')] += 1; used.add(t)
        if att[f]['method'] == 'key recovered from ciphertext-only' and att[f]['ok']:
            n_ok += 1
            for t in used: tech_ok[t] += 1
    rows = []
    for t, c in sorted(tech.items(), key=lambda x: -sum(x[1].values())):
        n = sum(c.values())
        if n < 5: continue
        rows.append((t, n, f'{100 * c["worked"] // n}%', f'{100 * c["partial"] // n}%',
                     f'{100 * (c["failed"] + c["ruled out"]) // n}%', f'{tech_ok[t]}/{n_ok}'))
    md += ['## 2. Which techniques work', '',
           'Attack steps only (solver, hypothesis, crib, sibling key, key from source, statistics). The last column '
           'counts the successful ciphertext-only key recoveries whose record uses the technique at all.', '',
           mine.table(['technique', 'steps', 'worked', 'partial', 'failed or ruled out', 'in CT-only successes'], rows), '']

    # 3. where the work fails
    kinds = C.defaultdict(C.Counter); before = []; heavy = []
    for f, p in profs.items():
        if f not in att: continue
        steps = [s for s in p.get('solution') or [] if isinstance(s, dict)]
        for s in steps: kinds[s.get('kind')][s.get('result')] += 1
        fails = sum(1 for s in steps if s.get('result') in ('failed', 'ruled out'))
        first = next((i for i, s in enumerate(steps) if s.get('kind') in ('reading', 'solver', 'sibling key', 'key from source')
                      and s.get('result') == 'worked'), None)
        if first is not None and att[f]['ok']:
            before.append(sum(1 for s in steps[:first] if s.get('result') in ('failed', 'ruled out')))
        heavy.append((fails, len(steps), f, att[f]['class'], att[f]['method']))
    rows = [(k, sum(c.values()), f'{100 * (c["failed"] + c["ruled out"]) // max(1, sum(c.values()))}%')
            for k, c in sorted(kinds.items(), key=lambda x: -sum(x[1].values())) if k]
    md += ['## 3. Where the work fails', '', mine.table(['step kind', 'steps', 'failed or ruled out'], rows), '']
    if before:
        before.sort()
        md += [f'Failed steps before the first step that worked, on successful targets: median {before[len(before) // 2]}, '
               f'90th percentile {before[int(len(before) * .9)]}, max {before[-1]} (n = {len(before)}).', '']
    heavy.sort(reverse=True)
    md += ['Targets with the most failed steps (where effort went):', '',
           mine.table(['failed', 'steps', 'target', 'class', 'method'], [(a, b, c, d, e) for a, b, c, d, e in heavy[:15]]), '']

    # 4. clean the leads: drop keys the NOTES already mention for that target
    lp = OUT / 'leads.csv'
    kw = json.loads((ROOT / 'docs' / 'keys.json').read_text(encoding='utf-8'))
    keys = {k['id']: k for k in kw['keys']}
    src = C.defaultdict(set)
    for l in kw.get('source_links', []): src[l['key']].add(l['source'])
    leads = list(csv.DictReader(open(lp, encoding='utf-8')))
    kept, dropped = [], []
    for r in leads:
        notes = ''
        for n in ('NOTES.md',):
            q = ROOT / 'targets' / r['target'] / n
            if q.exists(): notes = q.read_text(encoding='utf-8', errors='replace')
        k = keys.get(r['key'], {})
        marks = {r['key']} | set(re.findall(r'\bR\d{3,5}\b', r['key'].upper().replace('K-R', 'R')))
        marks |= set(re.findall(r'\bR\d{3,5}\b', k.get('label', '')))
        hit = next((m for m in marks if m and re.search(r'(?<![\w-])' + re.escape(m) + r'(?![\w-])', notes, re.I)), None)
        if not hit:                          # a key from the same source already read this target (e.g. two Lasry tables)
            used = {l['key'] for l in kw['links'] if l['target'] == r['target']}
            same = src.get(r['key'], set()) - {'s-cyphersolver'}
            if any(same & src.get(u, set()) for u in used): hit = 'same source as ' + ', '.join(sorted(used))
        (dropped if hit else kept).append({**r, 'mentioned_as': hit or ''})
    with open(lp, 'w', newline='', encoding='utf-8') as fh:
        cols = list(leads[0]) + ['status'] if leads else ['target']
        w = csv.DictWriter(fh, fieldnames=cols, extrasaction='ignore')
        w.writeheader()
        for r in kept: w.writerow({**r, 'status': 'untried'})
        for r in dropped: w.writerow({**r, 'status': f'notes mention {r["mentioned_as"]}'})
    tops = {}
    for r in kept: tops.setdefault(r['target'], r)
    md += ['## 4. Leads after checking the notes', '',
           f'Of {len(leads)} leads, {len(dropped)} name a key or record that the target\'s NOTES.md already mentions, or come from the same source as a key that already read the target '
           f'(tried or redundant; log real trials in keys.json "tried"). {len(kept)} leads on {len(tops)} '
           'targets remain untried as far as the record shows. Best remaining per target:', '',
           mine.table(['target', 'state', 'country', 'year', 'key', 'look-alikes', 'score'],
                      [(r['target'], r['class'], r['country'], r['year'], r['key'], r['via'], r['score'])
                       for r in sorted(tops.values(), key=lambda r: -float(r['score']))[:25]]), '']
    (OUT / 'DEEPER.md').write_text('\n'.join(md) + '\n', encoding='utf-8')
    print(f'{len(att)} attempted targets; leads {len(leads)} -> {len(kept)} untried on {len(tops)} targets -> research/patterns/DEEPER.md')

if __name__ == '__main__':
    main()
